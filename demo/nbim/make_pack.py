HEAD = PatternFill("solid", fgColor="1F3A5F")


def build(out: Path) -> Path:
    wb = Workbook()
    wb.remove(wb.active)
    for bid, (title, header, rows) in DATA.items():
        spec = BLOCKS[bid]
        ws = wb.create_sheet(spec["sheet"])
        ws.append([title])
        ws.append([f"(단위: {spec['unit']})"])
        ws.append(header)
        for c in ws[3]:
            c.font = Font(bold=True, color="FFFFFF")
            c.fill = HEAD
            c.alignment = Alignment(horizontal="center")
        for r in rows:
            ws.append(["-" if v is None else v for v in r])
            for c in ws[ws.max_row][1:]:
                if isinstance(c.value, (int, float)):
                    c.number_format = spec["number"]
        ws.column_dimensions["A"].width = 30
        for col in "BCDEF":
            ws.column_dimensions[col].width = 16
    wb.properties.title = "NBIM 2025 상반기 성과 데이터"
    wb.properties.creator = "NBIM 공개 보고서(Half-year report 2025)에서 옮김"
    wb.save(out)
    return out


