def row_spec(label: str) -> Optional[Dict[str, Any]]:
    """행 이름 → 행 종류 사양. 증가율 행이면 {"growth": True}. 모르면 None(빈 칸)."""
    k = _key(label)
    if k in _GROWTH:
        return {"growth": True}
    return ROWS.get(k)


