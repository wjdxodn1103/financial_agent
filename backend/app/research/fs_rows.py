def asof_spec(label: str) -> Optional[Dict[str, Any]]:
    k = _key(label)
    return next((s for p, s in ASOF if k.startswith(p)), None)


# ── 기간 수익률 표(Stock Data — 행 절대·상대, 열 1·6·12개월) ──────────────────
def returns_metric(row_label: str, col_label: str) -> Optional[str]:
    """('절대주가', '6개월') → '6개월수익률', ('상대주가', '12개월') → '1년상대수익률'(주가 스냅샷의 metric_key)."""
    k = _key(row_label)
    tail = "상대수익률" if k.startswith("상대") else "수익률" if k.startswith("절대") else ""
    m = re.match(r"(\d+)\s*(개월|m|M)", col_label or "")
    if not tail or not m:
        return None
    n = int(m.group(1))
    return f"{'1년' if n == 12 else f'{n}개월'}{tail}"


